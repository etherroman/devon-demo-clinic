CREATE TABLE IF NOT EXISTS owners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    telephone VARCHAR(30) NOT NULL,
    address VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50) NOT NULL,
    birth_date DATE NOT NULL,
    CONSTRAINT fk_pets_owner FOREIGN KEY (owner_id) REFERENCES owners(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_pets_owner ON pets(owner_id);
CREATE TABLE IF NOT EXISTS visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL,
    visit_date DATE NOT NULL,
    description VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_visits_pet FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_visits_pet ON visits(pet_id);
